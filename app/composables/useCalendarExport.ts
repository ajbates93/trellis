export const useCalendarExport = () => {
  /**
   * Format date to iCal format (YYYYMMDDTHHMMSSZ)
   */
  const formatICalDate = (date: Date): string => {
    return date.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  };

  /**
   * Generate iCal file content from review data
   */
  const generateICalContent = (review: {
    id: string;
    name: string;
    scheduledDate: string;
    notes?: string | null;
    user?: { name: string };
    buddy?: { name: string };
  }): string => {
    const scheduledDate = new Date(review.scheduledDate);
    const currentDate = new Date();

    // Build description with review details
    const description = [
      review.notes || "",
      `\\n\\nReviewee: ${review.user?.name || "N/A"}`,
      `Buddy: ${review.buddy?.name || "N/A"}`,
      `\\n\\nGenerated by Trellis Review Scheduler`,
    ]
      .join("")
      .replace(/\n/g, "\\n");

    // iCal content (RFC 5545 compliant)
    const icalContent = [
      "BEGIN:VCALENDAR",
      "VERSION:2.0",
      "PRODID:-//Trellis//Review Scheduler//EN",
      "CALSCALE:GREGORIAN",
      "METHOD:PUBLISH",
      "BEGIN:VEVENT",
      `UID:review-${review.id}@trellis.app`,
      `DTSTAMP:${formatICalDate(currentDate)}`,
      `DTSTART:${formatICalDate(scheduledDate)}`,
      `SUMMARY:${review.name}`,
      `DESCRIPTION:${description}`,
      "STATUS:CONFIRMED",
      "END:VEVENT",
      "END:VCALENDAR",
    ].join("\r\n"); // RFC 5545 requires CRLF

    return icalContent;
  };

  /**
   * Download iCal file
   */
  const downloadICalFile = (review: any) => {
    const icalContent = generateICalContent(review);
    const blob = new Blob([icalContent], {
      type: "text/calendar;charset=utf-8",
    });
    const url = URL.createObjectURL(blob);

    // Create download link
    const link = document.createElement("a");
    link.href = url;
    link.download = `review-${review.name.replace(/\s+/g, "-").toLowerCase()}.ics`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return {
    downloadICalFile,
  };
};
